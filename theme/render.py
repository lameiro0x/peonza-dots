#!/usr/bin/env python3
"""Render every app theme, once per theme, from contracts/themes/<id>.json.

Every app config that carries a colour, a font or a radius is a template in
theme/templates/, rendered three times into themes/<id>/<same relative path>.
At runtime ~/.local/state/ryce/theme/current points at one of those directories
and install/links.tsv `theme` rows link each app's config file through it, so a
theme switch is one atomic rename (bin/ryce-theme). Behaviour-only configs (fish
functions, fontconfig, GTK settings.ini, qt6ct.conf, portals) stay hand-written
in apps/.

    python3 theme/render.py           write themes/<id>/<rel> for every template
    python3 theme/render.py --check   exit 1 if any is stale, missing or orphaned

Placeholders:

    {{bg1}}                 #0e0c0a           any colour role of the theme
    {{bg1.hex}}             0e0c0a
    {{bg1.rgb}}             14, 12, 10
    {{bg1@0.5}}             #0e0c0a80         #rrggbbaa (mako, rofi, VS Code)
    {{bg1@alpha.panel}}     alpha taken from the theme's `alpha` block
    {{ansi.4}} {{ansi.4.hex}}                 ANSI slot 0..15
    {{alpha.term}}          0.96
    {{font.ui}} {{font.display}} {{font.mono}} {{font.icon}}
    {{geometry.rounding}}   10                 any geometry key
    {{blur.size}} {{motion.ms}}
    {{theme.id}} {{theme.name}} {{theme.tagline}}
    {{theme.scheme}}        light | dark (bg0's polarity: nvim background, Claude Code base)
    {{hue.cpu}} {{hue.cpu.hex}}             a bar module's colour (hues block)
    {{term.diff_add}}                       terminal extras (term block)
    {{glyph.uF0349}}                        any code point as a character

A theme's own version of a template lives at theme/templates/@<id>/<same path>
and replaces the shared one for that theme only.
    {{desktop.icon_theme}}  ryce-origen        any desktop key
    {{glyph.magnify}}       an nf-md glyph as a character (glyphs are never typed)
    {{glyph.peonza}}        U+100000, the Ryce Peonza font's mark
    {{clock.sep}}           the hour:minute separator that reads well in the display font

`signal`, `signal_dim` and `signal_on_pill` mean one thing (an AI session waits
for you) and are refused everywhere except the templates in SIGNAL_TEMPLATES.
fg2 is for marks (borders, separators, trails), never for text.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from tokens import ThemeError, load_all, scheme  # noqa: E402

TEMPLATES = ROOT / "theme" / "templates"
THEMES_OUT = ROOT / "themes"
HEADER_MARK = "GENERATED by theme/render.py"
REFUSED = {"signal", "signal_dim", "signal_on_pill"}
# The lock screen and the boot surfaces may say «an agent waits for you».
SIGNAL_TEMPLATES = {"hypr/hyprlock.conf"}
LEGACY = {"white": "pill", "ink_on_white": "ink_on_pill", "dim_on_white": "dim_on_pill"}
LEGACY_FONTS = {"pixel": "display"}
TOKEN = re.compile(r"\{\{\s*([^{}]+?)\s*\}\}")

# nf-md-* codepoints (Nerd Fonts 3.x == Material Design Icons codepoints).
GLYPHS = {
    "magnify": 0xF0349,
    "chevron_right": 0xF0142,
    "source_branch": 0xF062C,
    "arch": 0xF08C7,
    "linux": 0xF033D,
    "chip": 0xF061A,
    "timer_outline": 0xF051B,
    "package_variant": 0xF03D6,
    "console_line": 0xF07B7,
    "dock_window": 0xF10AC,
    "cpu_64_bit": 0xF0EE0,
    "expansion_card": 0xF08AE,
    "memory": 0xF035B,
    "harddisk": 0xF02CA,
    "monitor": 0xF0379,
    "palette_outline": 0xF0E0C,
    "weather_night": 0xF0594,
    "folder": 0xF024B,
    "clock_outline": 0xF0150,
    "content_paste": 0xF0192,
    "apps": 0xF003B,
    "lock_outline": 0xF0341,
    "peonza": 0x100000,
    "peonza32": 0x100001,
    "peonza64": 0x100002,
}

# Comment syntax per output, by suffix or by file name. QSettings (qt6ct) only
# knows `;`; GTK CSS has no line comments; JSON has none at all (VS Code themes
# are built by theme/vscode/build.py, not here).
COMMENT = {
    ".conf": ("#", ""), ".toml": ("#", ""), ".theme": ("#", ""), "config": ("#", ""),
    ".jsonc": ("//", ""), ".rasi": ("/*", " */"), ".css": ("/*", " */"), ".fish": ("#", ""),
    ".lua": ("--", ""), ".ini": (";", ""), ".script": ("#", ""), ".txt": ("#", ""),
    ".plymouth": ("#", ""),
}
COMMENT_OVERRIDE = {"qt6ct/colors/ryce.conf": (";", "")}


class RenderError(Exception):
    pass


def _hex(v: str) -> str:
    if not re.fullmatch(r"#[0-9a-f]{6}", v):
        raise RenderError(f"`{v}` is not a colour")
    return v


def _resolve(expr: str, t: dict, rel: str) -> str:
    colors = t["colors"]
    if "@" in expr:
        name, a = expr.split("@", 1)
        base = _hex(_resolve(name, t, rel))
        alpha = t["alpha"].get(a[6:]) if a.startswith("alpha.") else None
        if alpha is None:
            try:
                alpha = float(a)
            except ValueError:
                raise RenderError(f"bad alpha `{a}`") from None
        if not 0 <= alpha <= 1:
            raise RenderError(f"alpha {alpha} outside 0..1")
        return f"{base}{round(alpha * 255):02x}"
    head, _, tail = expr.partition(".")
    head = LEGACY.get(head, head)
    if head in REFUSED and rel not in SIGNAL_TEMPLATES:
        raise RenderError(f"`{head}` is the AI-waiting signal; this template may not use it")
    if head in colors or head == "ansi":
        if head == "ansi":
            idx, _, form = tail.partition(".")
            if not (idx.isdigit() and int(idx) < 16):
                raise RenderError(f"unknown ANSI slot `{expr}`")
            v = t["ansi"][int(idx)]
        else:
            v, form = colors[head], tail
        if form == "":
            return v
        if form == "hex":
            return v[1:]
        if form == "rgb":
            return ", ".join(str(int(v[i:i + 2], 16)) for i in (1, 3, 5))
        raise RenderError(f"unknown colour form `{expr}`")
    if head in ("hue", "term"):
        key, _, form = tail.partition(".")
        block = t["hues" if head == "hue" else "term"]
        if key not in block:
            raise RenderError(f"unknown {head} colour `{expr}`")
        v = block[key]
        if form == "":
            return v
        if form == "hex":
            return v[1:]
        if form == "rgb":
            return ", ".join(str(int(v[i:i + 2], 16)) for i in (1, 3, 5))
        raise RenderError(f"unknown colour form `{expr}`")
    if head == "wallpaper" and tail in ("transition", "scene", "grade"):
        return str(t["wallpaper"][tail])
    if head == "alpha" and tail in t["alpha"]:
        return str(t["alpha"][tail])
    if head == "font":
        key = LEGACY_FONTS.get(tail, tail)
        if key in t["fonts"]:
            return str(t["fonts"][key])
    if head == "geometry" and tail in t["geometry"]:
        return str(t["geometry"][tail])
    if head == "blur" and tail in t["blur"]:
        v = t["blur"][tail]
        return ("true" if v else "false") if isinstance(v, bool) else str(v)
    if head == "motion" and tail in ("ms", "preset"):
        return str(t["motion"][tail])
    if head == "theme" and tail == "scheme":
        return scheme(t)
    if head == "theme" and tail in ("id", "name", "tagline", "temperature"):
        return str(t[tail])
    if head == "desktop" and tail in t["desktop"]:
        return str(t["desktop"][tail])
    if head == "clock" and tail == "sep":
        # Doto draws ':' as a dotted dagger; its middle dot reads as the separator.
        return "\u00b7" if t["fonts"]["display"] == "Doto" else ":"
    if head == "glyph" and tail in GLYPHS:
        return chr(GLYPHS[tail])
    if head == "glyph" and re.fullmatch(r"u[0-9a-fA-F]{4,6}", tail):
        return chr(int(tail[1:], 16))     # any code point: {{glyph.uF0349}}
    raise RenderError(f"unknown token `{expr}`")


def render_text(text: str, t: dict, rel: str) -> str:
    out = []
    for n, line in enumerate(text.split("\n"), 1):
        try:
            out.append(TOKEN.sub(lambda m: _resolve(m.group(1), t, rel), line))
        except RenderError as e:
            raise RenderError(f"theme/templates/{rel}:{n} ({t['id']}): {e}") from None
    return "\n".join(out)


def header(rel: str, t: dict) -> str:
    key = Path(rel).suffix or Path(rel).name
    plain = rel.split("/", 1)[1] if rel.startswith("@") else rel
    open_, close = COMMENT_OVERRIDE.get(plain) or COMMENT.get(key) or (None, None)
    if open_ is None:
        raise RenderError(f"{rel}: no comment syntax known; add it to COMMENT in theme/render.py")
    return (f"{open_} {HEADER_MARK} — theme «{t['name']}». Edit theme/templates/{rel} or"
            f" contracts/themes/{t['id']}.json and re-run it.{close}\n")


def templates() -> list[str]:
    """The shared templates (every theme renders them). theme/templates/@<id>/ holds a
    theme's own versions: same relative path, used instead of the shared one."""
    return sorted(p.relative_to(TEMPLATES).as_posix() for p in TEMPLATES.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts
                  and not p.relative_to(TEMPLATES).parts[0].startswith("@"))


def own_templates(tid: str) -> list[str]:
    d = TEMPLATES / f"@{tid}"
    return sorted(p.relative_to(d).as_posix() for p in d.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts) if d.is_dir() else []


def render_all(themes: dict[str, dict]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    strays = [p.name[1:] for p in TEMPLATES.glob("@*") if p.name[1:] not in themes]
    if strays:
        raise RenderError(f"theme/templates/@{strays[0]}: no such theme in contracts/themes")
    for tid, t in themes.items():
        own = set(own_templates(tid))
        for rel in sorted(set(templates()) | own):
            src_path = TEMPLATES / f"@{tid}" / rel if rel in own else TEMPLATES / rel
            src = src_path.read_text(encoding="utf-8")
            where = src_path.relative_to(TEMPLATES).as_posix()
            # JSON has no comments: such outputs carry no header (and are never orphan-checked).
            head = "" if rel.endswith(".json") else header(where, t)
            out[THEMES_OUT / tid / rel] = head + render_text(src, t, rel)
    return out


def orphans(outputs: dict[Path, str]) -> list[str]:
    """Rendered files under themes/ whose template was deleted."""
    found = []
    for f in THEMES_OUT.rglob("*"):
        if f.is_file() and f not in outputs:
            try:
                head = f.read_text(encoding="utf-8")[:400]
            except (OSError, UnicodeDecodeError):
                continue
            if HEADER_MARK in head:
                found.append(f.relative_to(ROOT).as_posix())
    return sorted(found)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        outputs = render_all(load_all())
    except (RenderError, ThemeError) as e:
        print(f"render: {e}", file=sys.stderr)
        return 2
    bad = []
    for dst, text in outputs.items():
        if check:
            try:
                cur = dst.read_text(encoding="utf-8")
            except OSError:
                cur = None
            if cur != text:
                bad.append(f"stale: {dst.relative_to(ROOT)} (run python3 theme/render.py)")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(text, encoding="utf-8")
    if not check:
        print(f"render: wrote {len(outputs)} files ({len(templates())} templates x {len(outputs) // max(1, len(templates()))} themes)")
    bad += [f"orphan: {rel} is generated but has no template (delete it)" for rel in orphans(outputs)]
    for b in bad:
        print(b)
    if check and not bad:
        print(f"render: ok ({len(outputs)} files)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
