#!/usr/bin/env python3
"""Generate hypr/binds.lua from keys/keymap.tsv.

    python3 keys/gen.py           write hypr/binds.lua
    python3 keys/gen.py --check   exit 1 if hypr/binds.lua differs from the TSV

Standard library only. One session, Hyprland 0.57 (Lua config): no bspwm/sxhkd side.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import NamedTuple

KEYS = Path(__file__).resolve().parent
ROOT = KEYS.parent
KEYMAP = KEYS / "keymap.tsv"
LUA_OUT = ROOT / "hypr" / "binds.lua"

MOD_ORDER = ("CTRL", "SHIFT", "ALT", "SUPER")
DIRECTIONS = {"l": "left", "r": "right", "u": "up", "d": "down"}
# Next / previous, or the screen to the left / right.
MONITORS = ("+1", "-1", "l", "r")
MONITOR_ACTIONS = {"focusmonitor", "movetomonitor"}
# CTRL + 1..9, 0 (contracts/constants.json workspace_keys).
WORKSPACES = range(1, 11)
STEPS = ("-1", "+1")

MOUSE_ACTIONS = {"drag", "dragresize"}
NO_ARG = {"close", "fullscreen", "float", "pseudo", "togglesplit", "exit", *MOUSE_ACTIONS}
ACTIONS = NO_ARG | MONITOR_ACTIONS | {"exec", "focus", "move", "resize", "workspace",
                                      "movetoworkspace", "wsstep", "call"}
# `call` runs a function another hypr/*.lua module puts in the global `ryce` table.
CALLABLE = re.compile(r"ryce\.[a-z_][a-z0-9_]*")
# Hyprland bind options per TSV flag: locked = bindl, repeat = bindel.
FLAG_OPTS = {
    "locked": "{ locked = true }",
    "repeat": "{ locked = true, repeating = true }",
}

LUA_HEADER = f"""\
-- GENERATED by keys/gen.py from keys/keymap.tsv. Do not edit: change the TSV
-- and rerun the generator. hyprland.lua loads this file FIRST, so a broken
-- module later in the config never leaves the session without keys.
--
-- {{ locked = true }} is the Lua spelling of `bindl`, {{ locked = true,
-- repeating = true }} of `bindel`. {{ mouse = true }} follows
-- example/hyprland.lua at v0.57.1; drag() and resize() hold until release.

-- Each screen keeps its own workspaces: ~/.config/hypr/local.lua pins them with
-- persistent workspace rules (here 1-5 the main screen, 6-10 the second one).
--
-- ryce.ws_step(d): the dispatcher for the workspace one NUMBER after (d = 1) or
-- before (d = -1) the one showing on the focused screen, empty ones included
-- (Hyprland's e-1/e+1 skip those), or nil past 1 and {WORKSPACES[-1]}: it never wraps.
-- Stepping past a screen's last one goes on to the other screen (5 -> 6 takes
-- the focus to the second screen, 6 -> 5 back): focusing N goes to the screen
-- that keeps N, and a workspace that does not exist yet opens where its rule
-- puts it. A global, so a Lua `hyprctl dispatch` can call it too. On a cleared
-- desk (hypr/despejar.lua shows `despejado-N` in place of N) it steps from N, as
-- if N were still showing; on any other named workspace it does nothing.
ryce = ryce or {{}}
function ryce.ws_step(d)
    local w = hl.get_active_workspace()
    local id = w and w.id
    if not id or id <= 0 then
        id = tonumber(w and w.name and w.name:match("^despejado%-(%d+)$") or "")
    end
    if not id then return nil end
    -- Clamped, and only ever in the direction asked (from a stray 12, back to {WORKSPACES[-1]}).
    local n = math.max(1, math.min({WORKSPACES[-1]}, id + d))
    if (n - id) * d <= 0 then return nil end
    return hl.dsp.focus({{ workspace = n }})
end
"""


class KeymapError(Exception):
    pass


class Bind(NamedTuple):
    line: int
    mods: tuple[str, ...]
    key: str
    action: str
    arg: str
    flag: str

    @property
    def combo(self) -> str:
        return " + ".join((*self.mods, self.key))


def _check_arg(action: str, arg: str) -> str | None:
    """Why `arg` is invalid for `action`, or None if it is fine."""
    if action in ("focus", "move") and arg not in DIRECTIONS:
        return f"direction must be one of {', '.join(DIRECTIONS)}"
    if action in MONITOR_ACTIONS and arg not in MONITORS:
        return f"monitor must be one of {', '.join(MONITORS)}"
    if action in ("workspace", "movetoworkspace") and not (arg.isdigit() and int(arg) in WORKSPACES):
        return f"workspace must be {WORKSPACES[0]}-{WORKSPACES[-1]}"
    if action == "wsstep" and arg not in STEPS:
        return f"wsstep must be one of {', '.join(STEPS)}"
    if action == "call" and not CALLABLE.fullmatch(arg):
        return "call takes a function name such as ryce.despejar"
    if action == "resize":
        try:
            dx, dy = (int(v) for v in arg.split())
        except ValueError:
            return "resize takes two integers, e.g. -40 0"
        if (dx == 0) == (dy == 0):
            return "resize must change exactly one axis"
    return None


def parse(text: str, source: str = "keymap.tsv") -> list[Bind]:
    binds: list[Bind] = []
    seen: dict[tuple[tuple[str, ...], str], int] = {}
    for n, raw in enumerate(text.splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        where = f"{source}:{n}"
        fields = [f.strip() for f in raw.split("\t") if f.strip()]
        if len(fields) not in (4, 5):
            raise KeymapError(f"{where}: expected 4 or 5 TAB-separated fields "
                              f"(mods key action arg [flag]), got {len(fields)}")
        mods_field, key, action, arg = fields[:4]
        mods = () if mods_field == "-" else tuple(mods_field.split())
        flag = fields[4] if len(fields) == 5 else ""

        if unknown := [m for m in mods if m not in MOD_ORDER]:
            raise KeymapError(f"{where}: unknown modifier {unknown[0]!r} (use {', '.join(MOD_ORDER)} or -)")
        if len(set(mods)) != len(mods):
            raise KeymapError(f"{where}: modifier repeated in {mods_field!r}")
        if {"ALT", "SHIFT"} <= set(mods):
            raise KeymapError(f"{where}: ALT with SHIFT also switches the keyboard layout "
                              "(grp:alt_shift_toggle in hypr/look.lua); pick other modifiers")
        mods = tuple(sorted(mods, key=MOD_ORDER.index))
        if action not in ACTIONS:
            raise KeymapError(f"{where}: unknown action {action!r}")
        if flag and flag not in FLAG_OPTS:
            raise KeymapError(f"{where}: unknown flag {flag!r} (one of: {', '.join(FLAG_OPTS)})")
        arg = "" if arg == "-" else arg
        if (action in NO_ARG) == bool(arg):
            raise KeymapError(f"{where}: {action} takes {'no argument (use -)' if action in NO_ARG else 'an argument'}")
        if (action in MOUSE_ACTIONS) != key.startswith("mouse:"):
            raise KeymapError(f"{where}: mouse:<button> keys go with drag/dragresize and only with them")
        if flag and action in MOUSE_ACTIONS:
            raise KeymapError(f"{where}: mouse binds take no flag")
        if problem := _check_arg(action, arg):
            raise KeymapError(f"{where}: {problem}, got {arg!r}")

        bind = Bind(n, mods, key, action, arg, flag)
        if (mods, key.lower()) in seen:
            raise KeymapError(f"{where}: {bind.combo} is already bound on line {seen[(mods, key.lower())]}")
        seen[(mods, key.lower())] = n
        binds.append(bind)
    if not binds:
        raise KeymapError(f"{source}: no bindings found")
    return binds


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_dispatch(b: Bind) -> str:
    a, arg = b.action, b.arg
    if a == "exec":
        return f"hl.dsp.exec_cmd({lua_str(arg)})"
    if a in ("focus", "move"):
        fn = "hl.dsp.focus" if a == "focus" else "hl.dsp.window.move"
        return f'{fn}({{ direction = "{DIRECTIONS[arg]}" }})'
    if a == "resize":
        dx, dy = (int(v) for v in arg.split())
        return f"hl.dsp.window.resize({{ x = {dx}, y = {dy}, relative = true }})"
    if a in ("workspace", "movetoworkspace"):
        fn = "hl.dsp.focus" if a == "workspace" else "hl.dsp.window.move"
        return f"{fn}({{ workspace = {arg} }})"
    if a == "wsstep":
        # Evaluated per press: the target depends on the workspace you are on. Past the
        # screen's edge there is none and the key does nothing.
        return f"function() local s = ryce.ws_step({int(arg)}) if s then hl.dispatch(s) end end"
    if a == "call":
        # Looked up per press: the module that defines it loads after binds.lua.
        return f"function() {arg}() end"
    if a in MONITOR_ACTIONS:
        fn = {"focusmonitor": "hl.dsp.focus", "movetomonitor": "hl.dsp.window.move"}[a]
        call = f"{fn}({{ monitor = {lua_str(arg)} }})"
        if arg in ("+1", "-1"):
            return call
        # A side: at the edge there is no screen there, and the bare dispatch would raise
        # Hyprland's «Invalid monitor» error banner. hl.get_monitor resolves "l"/"r" from
        # the focused screen, as the dispatcher does; nil means do nothing.
        return f"function() if hl.get_monitor({lua_str(arg)}) then hl.dispatch({call}) end end"
    return {
        "close": "hl.dsp.window.close()",
        "fullscreen": "hl.dsp.window.fullscreen()",
        "float": 'hl.dsp.window.float({ action = "toggle" })',
        "pseudo": "hl.dsp.window.pseudo()",
        "togglesplit": 'hl.dsp.layout("togglesplit")',
        "exit": "hl.dsp.exit()",
        "drag": "hl.dsp.window.drag()",
        "dragresize": "hl.dsp.window.resize()",
    }[a]


def render_lua(binds: list[Bind]) -> str:
    lines = [LUA_HEADER]
    for b in binds:
        opts = ""
        if b.flag:
            opts = ", " + FLAG_OPTS[b.flag]
        elif b.action in MOUSE_ACTIONS:
            opts = ", { mouse = true }"
        lines.append(f"hl.bind({lua_str(b.combo)}, {lua_dispatch(b)}{opts})")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate hypr/binds.lua from keys/keymap.tsv.")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if hypr/binds.lua is missing or stale")
    args = ap.parse_args(argv)

    try:
        binds = parse(KEYMAP.read_text(encoding="utf-8"), KEYMAP.name)
    except (OSError, KeymapError) as e:
        print(f"gen.py: {e}", file=sys.stderr)
        return 2

    text = render_lua(binds)
    rel = LUA_OUT.relative_to(ROOT)
    current = LUA_OUT.read_text(encoding="utf-8") if LUA_OUT.is_file() else None
    if args.check:
        if current != text:
            print(f"gen.py: stale: {rel} (run python3 keys/gen.py)", file=sys.stderr)
            return 1
        print(f"gen.py: ok: {len(binds)} binds; {rel} up to date")
        return 0

    if current != text:
        LUA_OUT.parent.mkdir(parents=True, exist_ok=True)
        LUA_OUT.write_text(text, encoding="utf-8")
        print(f"gen.py: wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
