#!/usr/bin/env python3
"""Validate the three theme contracts and generate the per-toolkit palette files.

One source per theme (contracts/themes/<id>.json, schema ryce.theme/2) for every
toolkit, so the compositor (Hyprland Lua), the fallback bar (GTK3) and the shell
(Quickshell/QML) cannot drift apart inside a theme, and the three themes cannot
drift apart in SHAPE: every theme must carry exactly the same key tree.

    python3 tools/tokens.py           write the generated files
    python3 tools/tokens.py --check   exit 1 if any generated file is stale, or a theme
                                      is missing a file of contracts/constants.json
                                      `theme_files` (run the other generators first)

Outputs (never edit by hand):
    themes/<id>/theme.json            normalised contract; Quickshell's Palette reads it
    themes/<id>/hypr/palette.lua      require("palette") from hyprland.lua (theme link)
    themes/<id>/waybar/palette.css    @import from the fallback bar's style.css (theme link)
    quickshell/ryce/Palette.qml       singleton: live palette, cross-fades on a switch
    quickshell/ryce/Words.qml         singleton: Words.state.busy ... (constants.json)

`signal` means one thing in every theme: an AI session is waiting for you.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from colormath import contrast, delta_e, luminance  # noqa: E402

THEMES_SRC = ROOT / "contracts" / "themes"
THEMES_OUT = ROOT / "themes"
CONSTANTS = ROOT / "contracts" / "constants.json"
HEADER = "GENERATED by tools/tokens.py from the theme contracts in contracts/themes — do not edit."
HEX = re.compile(r"^#[0-9a-f]{6}$")
SCHEMA = "ryce.theme/2"

COLOR_KEYS = ("bg0", "bg1", "bg2", "bg3", "line", "fg0", "fg1", "fg2",
              "pill", "ink_on_pill", "dim_on_pill", "busy",
              "signal", "signal_dim", "signal_on_pill", "tint", "ok", "warn", "err", "claude")
SIGNAL = ("signal", "signal_dim", "signal_on_pill")
# One colour per bar module (grey in the monochrome themes); never the signal.
HUE_KEYS = ("cpu", "mem", "net", "vol", "media", "clock", "disk")
# Terminal extras the 16 ANSI slots cannot carry (kitty, Claude Code, delta).
TERM_KEYS = ("cursor", "selection_bg", "selection_fg", "url", "claude", "diff_add", "diff_del",
             "diff_add_word", "diff_del_word")
AMBIENT = {"hud", "binclock", "edgeviz"}     # desktop widgets quickshell/ryce/desk knows
# Every colour some app sets letters in (fg2 included: comments, hints, inactive tabs,
# placeholders), held to the text floor on the two grounds text sits on.
TEXT_ROLES = ("fg0", "fg1", "fg2", "busy", "tint", "ok", "warn", "err", "claude")
TEXT_TERM = ("url", "claude")


class ThemeError(Exception):
    pass


def constants() -> dict:
    return json.loads(CONSTANTS.read_text(encoding="utf-8"))


def theme_ids() -> list[str]:
    return list(constants()["themes"])


def default_theme() -> str:
    return constants()["default_theme"]


def _shape(v) -> object:
    """The key tree of a JSON value, leaves reduced to their type name."""
    if isinstance(v, dict):
        return {k: _shape(x) for k, x in v.items()}
    if isinstance(v, list):
        return ["list"]
    if v is None:
        return "str"        # an optional path (wallpaper.source): null or a string
    return type(v).__name__ if not isinstance(v, (int, float)) or isinstance(v, bool) else "number"


def _fail(tid: str, msg: str) -> None:
    raise ThemeError(f"contracts/themes/{tid}.json: {msg}")


def validate(t: dict) -> None:
    tid = t.get("id", "?")
    if t.get("schema") != SCHEMA:
        _fail(tid, f"schema must be {SCHEMA!r}")
    c = t["colors"]
    if tuple(c) != COLOR_KEYS:
        _fail(tid, f"colors must be exactly, in order: {', '.join(COLOR_KEYS)}")
    for k, v in c.items():
        if not HEX.match(v):
            _fail(tid, f"colors.{k}={v!r} is not #rrggbb lowercase")
    if len(t["ansi"]) != 16 or not all(HEX.match(v) for v in t["ansi"]):
        _fail(tid, "ansi must be 16 #rrggbb lowercase colours")
    floor = t["contrast_floor"]
    for k in ("fg0", "fg1"):
        for bg in ("bg0", "bg1", "bg2"):
            if contrast(c[k], c[bg]) < floor["text"]:
                _fail(tid, f"{k} on {bg} is {contrast(c[k], c[bg]):.2f}:1, under the text floor {floor['text']}")
    if floor["text"] < 4.5 or floor["ui"] < 3.0:
        _fail(tid, "contrast_floor may not go under WCAG AA (text 4.5, ui 3.0)")
    text = {k: c[k] for k in TEXT_ROLES} | {f"term.{k}": t["term"][k] for k in TEXT_TERM}
    for bg in ("bg0", "bg1"):
        for k, v in text.items():
            if contrast(v, c[bg]) < floor["text"]:
                _fail(tid, f"{k} on {bg} is {contrast(v, c[bg]):.2f}:1, under the text floor {floor['text']}")
    for k in ("ink_on_pill",):
        if contrast(c[k], c["pill"]) < floor["text"]:
            _fail(tid, f"{k} on pill is under the text floor")
    if contrast(c["dim_on_pill"], c["pill"]) < floor["ui"]:
        _fail(tid, "dim_on_pill on pill is under the mark floor")
    for bg in ("bg0", "bg1", "bg3"):
        if contrast(c["signal"], c[bg]) < floor["ui"]:
            _fail(tid, f"signal on {bg} is {contrast(c['signal'], c[bg]):.2f}:1, under {floor['ui']}")
    if contrast(c["signal_on_pill"], c["pill"]) < floor["ui"]:
        _fail(tid, "signal_on_pill on pill is under the mark floor")
    # The signal must not look like anything else on screen: far from every grey
    # role (ΔE2000 >= 20) and visibly apart from every terminal colour (>= 12).
    for k in ("fg0", "fg1", "fg2", "pill", "line", "busy", "tint"):
        if delta_e(c["signal"], c[k]) < 20:
            _fail(tid, f"signal is too close to {k} (ΔE {delta_e(c['signal'], c[k]):.1f} < 20)")
    for i, a in enumerate(t["ansi"]):
        if delta_e(c["signal"], a) < 12:
            _fail(tid, f"signal is too close to ansi[{i}] (ΔE {delta_e(c['signal'], a):.1f} < 12)")
    # Claude's mark in the bar (its spark; held to the text floor above): never mistaken
    # for the signal, which is what a Claude session waiting for you lights up.
    if delta_e(c["signal"], c["claude"]) < 12:
        _fail(tid, f"claude is too close to the signal (ΔE {delta_e(c['signal'], c['claude']):.1f} < 12)")
    hues = t["hues"]
    if tuple(hues) != HUE_KEYS:
        _fail(tid, f"hues must be exactly, in order: {', '.join(HUE_KEYS)}")
    for k, v in hues.items():
        if not HEX.match(v):
            _fail(tid, f"hues.{k}={v!r} is not #rrggbb lowercase")
        if delta_e(c["signal"], v) < 20:
            _fail(tid, f"hues.{k} is too close to the signal (ΔE {delta_e(c['signal'], v):.1f} < 20)")
        for bg in ("bg0", "bg1"):
            if contrast(v, c[bg]) < floor["text"]:
                _fail(tid, f"hues.{k} on {bg} is {contrast(v, c[bg]):.2f}:1, under the text floor")
    term = t["term"]
    if tuple(term) != TERM_KEYS:
        _fail(tid, f"term must be exactly, in order: {', '.join(TERM_KEYS)}")
    for k, v in term.items():
        if not HEX.match(v):
            _fail(tid, f"term.{k}={v!r} is not #rrggbb lowercase")
    for k in ("diff_add", "diff_del", "diff_add_word", "diff_del_word"):
        if contrast(c["fg0"], term[k]) < floor["text"]:
            _fail(tid, f"fg0 on term.{k} is under the text floor (diff lines are read on it)")
    w = t["wallpaper"]
    for k in ("source", "lock_source"):
        if w[k] is not None and not (ROOT / w[k]).is_file():
            _fail(tid, f"wallpaper.{k} {w[k]!r} does not exist")
    if w["source"] is None and w["scene"] == "photo":
        _fail(tid, "wallpaper.scene 'photo' needs wallpaper.source")
    alts = w["alternates"]
    if not isinstance(alts, list) or not all(isinstance(a, str) for a in alts):
        _fail(tid, "wallpaper.alternates is a list of paths (2560x1440 masters in assets/wallpapers/)")
    for a in alts:
        if not (ROOT / a).is_file():
            _fail(tid, f"wallpaper.alternates: {a!r} does not exist")
    if len(set(alts)) != len(alts) or w["source"] in alts:
        _fail(tid, "wallpaper.alternates repeats a picture (or the main one)")
    if not (len(w["focus"]) == 2 and all(0 <= f <= 1 for f in w["focus"])):
        _fail(tid, "wallpaper.focus is [x, y] in 0..1")
    if w["grade"] not in ("none", "mono"):
        _fail(tid, "wallpaper.grade is none or mono")
    unknown = set(t["desktop"]["ambient"]) - AMBIENT
    if unknown:
        _fail(tid, f"desktop.ambient: unknown widgets {sorted(unknown)}")
    g = t["geometry"]
    for k in ("frame_top", "frame_rim", "frame_radius", "gaps_in", "gaps_out", "border", "rounding", "pill_radius"):
        if not isinstance(g[k], int) or g[k] < 0:
            _fail(tid, f"geometry.{k} must be a non-negative integer")
    # Hyprland's kawase blur: size x passes, then the result scaled by brightness. Only a
    # darkening (smoked glass): the terminal's text floor is measured under it
    # (theme/tests/test_terminal.py).
    b = t["blur"]
    if not (isinstance(b["size"], int) and b["size"] >= 1 and isinstance(b["passes"], int) and 1 <= b["passes"] <= 4):
        _fail(tid, "blur.size >= 1 and blur.passes 1..4 (integers)")
    if not 0.2 <= b["brightness"] <= 1.0:
        _fail(tid, "blur.brightness is 0.2..1.0")
    # The desk cards may stand on the sharp picture instead (Tinta's glass shows its sheet).
    if not isinstance(b.get("desk", True), bool):
        _fail(tid, "blur.desk is true or false")
    m = t["motion"]
    curves = m["hypr"]["curves"]
    for name, cv in curves.items():
        if cv["type"] == "bezier":
            if len(cv["points"]) != 2:
                _fail(tid, f"motion curve {name}: a bezier takes two control points")
        elif cv["type"] == "spring":
            for k in ("mass", "stiffness", "damping"):
                if not cv[k] > 0.5:
                    _fail(tid, f"motion curve {name}: {k} must be > 0.5 (Hyprland 0.57)")
        else:
            _fail(tid, f"motion curve {name}: type must be bezier or spring")
    for leaf, spec in m["hypr"]["leaves"].items():
        if spec["curve"] not in curves:
            _fail(tid, f"motion leaf {leaf} uses unknown curve {spec['curve']!r}")
    if len(m["qml_curve"]) != 6:
        _fail(tid, "motion.qml_curve is an Easing.BezierSpline list of 6 numbers")
    if t["wallpaper"]["animated"] is not False:
        _fail(tid, "wallpaper.animated ships false: the user enables it after seeing the measurement")


def load(tid: str) -> dict:
    p = THEMES_SRC / f"{tid}.json"
    t = json.loads(p.read_text(encoding="utf-8"))
    if t.get("id") != tid:
        _fail(tid, f"id must be {tid!r}")
    validate(t)
    return t


def load_all() -> dict[str, dict]:
    themes = {tid: load(tid) for tid in theme_ids()}
    def comparable(t: dict) -> dict:
        # Curve NAMES are per-theme data (a spring set vs a bezier set); everything
        # else, including the list of animation leaves, must match.
        d = {k: v for k, v in t.items() if k != "id"}
        d["motion"] = {**t["motion"], "hypr": {"leaves": t["motion"]["hypr"]["leaves"]}}
        return d

    shapes = {tid: _shape(comparable(t)) for tid, t in themes.items()}
    ref_id = next(iter(shapes))
    for tid, sh in shapes.items():
        if sh != shapes[ref_id]:
            raise ThemeError(f"contracts/themes/{tid}.json: key tree differs from {ref_id}.json "
                             "(every theme carries the same keys, so one QML property list fits all)")
    return themes


def scheme(t: dict) -> str:
    """"light" when the ground is paper (dark ink on it), else "dark". Derived from bg0, not
    a contract key, so a theme cannot claim one polarity and paint the other. GTK's
    colour-scheme, nvim's background, Claude Code's base, VS Code's uiTheme, the icon
    base and every shadow follow it."""
    return "light" if luminance(t["colors"]["bg0"]) > 0.5 else "dark"


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w.capitalize() for w in rest)


# ── outputs ───────────────────────────────────────────────────────────────────
def theme_json(t: dict) -> str:
    return json.dumps({**t, "scheme": scheme(t)}, indent=2, ensure_ascii=False) + "\n"


def _lua_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{ " + ", ".join(_lua_value(x) for x in v) + " }"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"[{json.dumps(k)}] = {_lua_value(x)}" for k, x in v.items()) + " }"
    raise TypeError(type(v))


def lua(t: dict) -> str:
    c = t["colors"]
    out = [f"-- {HEADER}",
           f"-- Theme «{t['name']}» ({t['id']}). Colours as Hyprland strings: P.bg1 = \"rgb(0e0c0a)\",",
           "-- P.hex.bg1 = \"0e0c0a\"; P.rgba(\"bg1\", 0.8) -> \"rgba(0e0c0acc)\".",
           "", "local P = { hex = {}, alpha = {}, ansi = {}, fonts = {}, geometry = {}, blur = {}, motion = {}, desktop = {} }", "",
           f"P.id = {json.dumps(t['id'])}", f"P.name = {json.dumps(t['name'], ensure_ascii=False)}",
           f"P.scheme = {json.dumps(scheme(t))}     -- \"light\": dark ink on paper (shadows in ink, not in bg0)", ""]
    for k, v in c.items():
        out.append(f'P.hex.{k} = "{v[1:]}"')
    out.append("")
    for k, v in c.items():
        out.append(f'P.{k} = "rgb({v[1:]})"')
    out.append("")
    for k, v in t["alpha"].items():
        out.append(f"P.alpha.{k} = {v!r}")
    for i, v in enumerate(t["ansi"]):
        out.append(f'P.ansi[{i}] = "{v[1:]}"')
    for k, v in t["fonts"].items():
        out.append(f"P.fonts.{k} = {_lua_value(v)}")
    for k, v in t["geometry"].items():
        out.append(f"P.geometry.{k} = {v!r}")
    for k, v in t["blur"].items():
        out.append(f"P.blur.{k} = {_lua_value(v)}")
    for k, v in t["desktop"].items():
        out.append(f"P.desktop.{k} = {_lua_value(v)}")
    out.append("P.hues = {}")
    for k, v in t["hues"].items():
        out.append(f'P.hues.{k} = "{v[1:]}"')
    out.append("P.term = {}")
    for k, v in t["term"].items():
        out.append(f'P.term.{k} = "{v[1:]}"')
    m = t["motion"]
    out.append(f"P.motion.preset = {json.dumps(m['preset'])}")
    out.append(f"P.motion.curves = {_lua_value(m['hypr']['curves'])}")
    out.append("P.motion.leaves = {")
    for leaf, spec in m["hypr"]["leaves"].items():
        out.append(f"    {leaf} = {_lua_value(spec)},")
    out.append("}")
    out += [
        "",
        "function P.rgba(name, a)",
        "    local h = P.hex[name]",
        "    assert(h, \"palette: unknown colour \" .. tostring(name))",
        "    local byte = math.floor(math.max(0, math.min(1, a)) * 255 + 0.5)",
        "    return string.format(\"rgba(%s%02x)\", h, byte)",
        "end",
        "",
        "return P",
        "",
    ]
    return "\n".join(out)


def css(t: dict) -> str:
    c = t["colors"]
    out = [f"/* {HEADER} */", f"/* Theme «{t['name']}». GTK3 named colours: @bg1, alpha(@bg1, 0.8). */", ""]
    for k, v in c.items():
        out.append(f"@define-color {k} {v};")
    for i, v in enumerate(t["ansi"]):
        out.append(f"@define-color ansi{i} {v};")
    for k, v in t["hues"].items():
        out.append(f"@define-color hue_{k} {v};")
    for k, v in t["term"].items():
        out.append(f"@define-color term_{k} {v};")
    out.append("")
    out.append(f"@define-color bar_bg alpha(@bg0, {t['alpha']['bar']});")
    out.append(f"@define-color tooltip_bg alpha(@bg1, {t['alpha']['tooltip']});")
    out.append("")
    return "\n".join(out)


def qml(themes: dict[str, dict]) -> str:
    """The live palette. Writable properties with the default theme's values; a
    FileView on state/current/theme.json re-applies on change, and the shell's
    `theme reload` IPC calls reload() explicitly (an inotify watch does not survive
    the atomic swap of the `current` link). Colours cross-fade over the new
    theme's motion duration."""
    t = themes[default_theme()]
    c = t["colors"]
    out = [f"// {HEADER}", "pragma Singleton", "", "import QtQuick", "import Quickshell", "import Quickshell.Io", "",
           "Singleton {", "    id: root", "",
           "    // RYCE_THEME_STATE lets tools/stage/nested.sh point a test shell at its own state.",
           "    readonly property string stateDir: Quickshell.env(\"RYCE_THEME_STATE\") || (Quickshell.env(\"HOME\") + \"/.local/state/ryce/theme\")",
           f"    readonly property var themeIds: {json.dumps(list(themes))}",
           "    // Every theme's face, for the selector. Static: it changes only when the contracts do.",
           "    readonly property var catalog: " + json.dumps({tid: {"name": th["name"], "tagline": th["tagline"], "fonts": th["fonts"],
               "colors": th["colors"], "hues": th["hues"], "rounding": th["geometry"]["rounding"], "pill_radius": th["geometry"]["pill_radius"]}
               for tid, th in themes.items()}, ensure_ascii=False),
           f"    property string themeId: {json.dumps(t['id'])}",
           f"    property string themeName: {json.dumps(t['name'], ensure_ascii=False)}",
           "    // Per-theme assets: through the theme's own directory, never through `current/`,",
           "    // so Qt's image cache and file watches see a new path when the theme changes.",
           "    readonly property string themeDir: stateDir + \"/\" + themeId",
           "    property bool loaded: false",
           "    signal switched()", ""]
    out.append(f"    property int motionMs: {t['motion']['ms']}")
    out.append(f"    property var motionCurve: {json.dumps(t['motion']['qml_curve'])}")
    out.append(f"    property string motionPreset: {json.dumps(t['motion']['preset'])}")
    out.append("    // Dark ink on a paper ground (Papel): shadows and raised text read the other way.")
    out.append(f"    property bool light: {'true' if scheme(t) == 'light' else 'false'}")
    out.append("")
    for k, v in c.items():
        out.append(f'    property color {camel(k)}: "{v}"')
    out.append("")
    for k, v in t["hues"].items():
        out.append(f'    property color hue{k.capitalize()}: "{v}"')
    out.append("")
    for k in c:
        out.append(f"    Behavior on {camel(k)} {{ ColorAnimation {{ duration: root.motionMs; easing.type: Easing.InOutQuad }} }}")
    for k in t["hues"]:
        out.append(f"    Behavior on hue{k.capitalize()} {{ ColorAnimation {{ duration: root.motionMs; easing.type: Easing.InOutQuad }} }}")
    out.append("")
    for k, v in t["alpha"].items():
        out.append(f"    property real alpha{k.capitalize()}: {v}")
    out.append(f"    property var ansi: {json.dumps(t['ansi'])}")
    for k, v in t["fonts"].items():
        kind = "int" if isinstance(v, int) else "string"
        out.append(f"    property {kind} font{camel(k)[0].upper() + camel(k)[1:]}: {json.dumps(v)}")
    for k, v in t["geometry"].items():
        kind = "real" if isinstance(v, float) else "int"
        out.append(f"    property {kind} {camel(k)}: {v}")
    out.append(f"    property bool blurEnabled: {'true' if t['blur']['enabled'] else 'false'}")
    out.append(f"    property real blurBrightness: {float(t['blur'].get('brightness', 1.0))}")
    out.append(f"    property bool blurDesk: {'true' if t['blur'].get('desk', True) else 'false'}")
    out.append(f"    property string wallpaperTransition: {json.dumps(t['wallpaper']['transition'])}")
    out.append(f"    property string wallpaperSource: {json.dumps(t['wallpaper'].get('source') or '')}")
    out.append(f"    property var ambient: {json.dumps(t['desktop']['ambient'])}")
    out.append("")
    out.append("    // Compatibility names for the widgets written before the three themes.")
    out.append("    readonly property color white: pill")
    out.append("    readonly property color inkOnWhite: inkOnPill")
    out.append("    readonly property color dimOnWhite: dimOnPill")
    out.append("    readonly property string fontPixel: fontDisplay")
    out.append("    readonly property int gapsOutLegacy: gapsOut")
    out.append("")
    out.append("    function rgba(col, a) { return Qt.rgba(col.r, col.g, col.b, a); }")
    out.append("")
    out.append("    function apply(t) {")
    out.append("        if (!t || t.schema !== \"ryce.theme/2\") return;")
    out.append("        motionMs = t.motion.ms;")
    out.append("        motionCurve = t.motion.qml_curve;")
    out.append("        motionPreset = t.motion.preset;")
    out.append("        light = t.scheme === \"light\";")
    for k in c:
        out.append(f"        {camel(k)} = t.colors.{k};")
    for k in t["alpha"]:
        out.append(f"        alpha{k.capitalize()} = t.alpha.{k};")
    out.append("        ansi = t.ansi;")
    for k in t["hues"]:
        out.append(f"        hue{k.capitalize()} = t.hues.{k};")
    out.append("        ambient = t.desktop.ambient;")
    for k in t["fonts"]:
        out.append(f"        font{camel(k)[0].upper() + camel(k)[1:]} = t.fonts.{k};")
    for k in t["geometry"]:
        out.append(f"        {camel(k)} = t.geometry.{k};")
    out.append("        blurEnabled = t.blur.enabled;")
    out.append("        blurBrightness = t.blur.brightness ?? 1;")
    out.append("        blurDesk = t.blur.desk ?? true;")
    out.append("        wallpaperTransition = t.wallpaper.transition;")
    out.append("        wallpaperSource = t.wallpaper.source ?? \"\";")
    out.append("        themeName = t.name;")
    out.append("        const changed = themeId !== t.id;")
    out.append("        themeId = t.id;")
    out.append("        loaded = true;")
    out.append("        if (changed) switched();")
    out.append("    }")
    out.append("")
    out.append("    function reload() { file.reload(); }")
    out.append("")
    out.append("    FileView {")
    out.append("        id: file")
    out.append("        path: root.stateDir + \"/current/theme.json\"")
    out.append("        watchChanges: true")
    out.append("        printErrors: false")
    out.append("        onFileChanged: reload()")
    out.append("        onLoaded: {")
    out.append("            try {")
    out.append("                root.apply(JSON.parse(text()));")
    out.append("            } catch (e) {")
    out.append("                console.warn(\"ryce palette: unreadable theme.json, keeping the current colours:\", e);")
    out.append("            }")
    out.append("        }")
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def words_qml() -> str:
    c = constants()["words_es"]
    out = ["// GENERATED by tools/tokens.py from contracts/constants.json (words_es) — do not edit.",
           "pragma Singleton", "", "import QtQuick", "import Quickshell", "", "Singleton {"]
    out.append(f"    readonly property var state: {json.dumps(c['state'], ensure_ascii=False)}")
    out.append(f"    readonly property var waitingFor: {json.dumps(c['waiting_for'], ensure_ascii=False)}")
    out.append(f"    readonly property string waitingFallback: {json.dumps(c['waiting_fallback'], ensure_ascii=False)}")
    out.append("}")
    out.append("")
    return "\n".join(out)


def targets(themes: dict[str, dict]) -> dict[Path, str]:
    out: dict[Path, str] = {}
    for tid, t in themes.items():
        base = THEMES_OUT / tid
        out[base / "theme.json"] = theme_json(t)
        out[base / "hypr" / "palette.lua"] = lua(t)
        out[base / "waybar" / "palette.css"] = css(t)
    out[ROOT / "quickshell" / "ryce" / "Palette.qml"] = qml(themes)
    out[ROOT / "quickshell" / "ryce" / "Words.qml"] = words_qml()
    return out


def missing_theme_files(themes: dict[str, dict]) -> list[str]:
    need = constants().get("theme_files", [])
    return [f"themes/{tid}/{rel}" for tid in themes for rel in need if not (THEMES_OUT / tid / rel).exists()]


def main(argv: list[str]) -> int:
    try:
        themes = load_all()
    except (ThemeError, KeyError) as e:
        print(f"tokens: {e}", file=sys.stderr)
        return 2
    check = "--check" in argv
    stale = []
    for path, text in targets(themes).items():
        if check:
            try:
                cur = path.read_text(encoding="utf-8")
            except OSError:
                cur = None
            if cur != text:
                stale.append(f"stale: {path.relative_to(ROOT)} (run python3 tools/tokens.py)")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if check:
        stale += [f"missing: {m} (constants.json theme_files; run the generators)" for m in missing_theme_files(themes)]
    for s in stale:
        print(s)
    if check and not stale:
        print(f"tokens: ok ({len(themes)} themes)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
