#!/usr/bin/env python3
"""Structural lint for the Quickshell `ryce` config, runnable without Qt.

    python3 quickshell/tests/qmlcheck.py quickshell/ryce contracts/roster.v1.schema.json

Exit 1 with one `file:line: problem` per violation. What it enforces:

1. CONTRACT. Every roster key the QML reads (`data.x`, `raw.x`, `session.x`,
   `Roster.counts.x`, chained) is a property name in the roster schema.
2. UNTRUSTED TEXT. Roster strings come from Claude transcripts: every `Text` sets
   `textFormat: Text.PlainText`, and nothing sets any other text format.
3. LAYER NAMES. Every `PanelWindow` sets `WlrLayershell.namespace: "qs-…"` (the
   Hyprland layer rules match `^qs-`).
4. FILE PATHS. A `FileView.path` is built only from string literals,
   `Quickshell.env(…)` and readonly string properties of the same file built the
   same way: never from roster data.
5. CAVA. The cava `Process` has a `running:` binding on visibility, never `true`.
6. PALETTE. No hex, `Qt.rgba(<number>…)` or named colours outside Palette.qml.
7. SIGNAL. `Palette.signal*` only under `agents/` (the waiting agent card) and `bar/`
   (the waiting slot dot, the agents counter, the peonza's wobble).
8. QUALIFIED PALETTE. QtQuick exports a `Palette` type that shadows the qs
   singleton, so a bare `Palette.x` is undefined at runtime: read tokens through
   `import qs as Ryce` → `Ryce.Palette.x`.
9. ONE VOCABULARY. A state word generated into Words.qml (contracts/constants.json
   words_es) is never typed as a literal elsewhere: bar and sidebar say the same.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROSTER_CHAIN = re.compile(r"(?<![\w.])(?:data|raw|session|Roster\.counts)((?:\??\.[A-Za-z_]\w*)+)")
# Members of JS values that end a roster key chain (`raw.doing.lines.slice`).
JS_MEMBERS = {
    "length", "map", "filter", "slice", "join", "some", "every", "find", "includes", "indexOf",
    "forEach", "reduce", "concat", "split", "trim", "toString", "toFixed", "push", "sort",
}
NAMESPACE = re.compile(r'WlrLayershell\.namespace\s*:\s*"qs-[a-z0-9-]+"')
PATH_BINDING = re.compile(r"(?<![\w.])path\s*:\s*([^;\n]+)")
RUNNING_BINDING = re.compile(r"(?<![\w.])running\s*:\s*([^;\n]+)")
VISIBILITY = re.compile(r"\b(shown|visible|open|active)\b")
COLOUR_LITERAL = re.compile(r'"#[0-9a-fA-F]{3,8}"|Qt\.(?:rgba|hsla|hsva)\(\s*[-\d.]|\bcolor\s*:\s*"(?!transparent")')
SIGNAL = re.compile(r"\bPalette\.signal")
BARE_PALETTE = re.compile(r"(?<![\w.])Palette\.")
# Generated by tools/tokens.py from contracts/: not ours to lint.
GENERATED = {"Palette.qml", "Words.qml"}
# Hand-written palettes that own their literals: the login page's fixed look (quickshell/greeter,
# which never follows the theme, so it has no generated Palette.qml).
PALETTES = {"Look.qml"}
IDENT_CHAIN = re.compile(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*")


def schema_keys(node: object) -> set[str]:
    """Every property name declared anywhere in the JSON schema."""
    keys: set[str] = set()
    if isinstance(node, dict):
        for name, sub in node.get("properties", {}).items():
            keys.add(name)
            keys |= schema_keys(sub)
        if "items" in node:
            keys |= schema_keys(node["items"])
    return keys


def mask(text: str, strings: bool) -> str:
    """Blank out comments (and string contents when `strings`), keeping offsets."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out[i:j] = " " * (j - i)
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out[i:j] = [ch if ch == "\n" else " " for ch in text[i:j]]
            i = j
        elif c in "\"'`":
            j = i + 1
            while j < n and text[j] != c:
                j += 2 if text[j] == "\\" else 1
            if strings:
                out[i + 1:j] = [ch if ch == "\n" else " " for ch in text[i + 1:j]]
            i = j + 1
        else:
            i += 1
    return "".join(out)


def blocks(code: str, type_name: str) -> list[tuple[int, slice]]:
    """(offset, body span) of every `TypeName { … }` object, nested ones included.
    The span indexes any masked copy of the same text: masking keeps offsets."""
    found = []
    for m in re.finditer(rf"(?<![\w.]){type_name}\s*\{{", code):
        depth, j = 0, m.end() - 1
        while j < len(code):
            depth += {"{": 1, "}": -1}.get(code[j], 0)
            if depth == 0:
                break
            j += 1
        found.append((m.start(), slice(m.end(), j)))
    return found


def safe_path(expr: str, props: dict[str, str], depth: int = 0) -> bool:
    if depth > 4:
        return False
    for ident in IDENT_CHAIN.findall(expr):
        if ident in ("Quickshell.env", "Quickshell.shellDir"):
            continue
        name = ident.rsplit(".", 1)[-1]
        if name not in props or not safe_path(props[name], props, depth + 1):
            return False
    return True


def check_file(path: Path, rel: str, keys: set[str], words: set[str]) -> list[str]:
    raw_text = path.read_text(encoding="utf-8")
    code = mask(raw_text, strings=False)      # comments gone, strings kept
    bare = mask(raw_text, strings=True)       # comments and string contents gone
    errs: list[str] = []

    def err(offset: int, msg: str) -> None:
        errs.append(f"{rel}:{raw_text.count(chr(10), 0, offset) + 1}: {msg}")

    for m in ROSTER_CHAIN.finditer(bare):
        for key in re.split(r"\??\.", m.group(1))[1:]:
            if key in JS_MEMBERS:
                break
            if key not in keys:
                err(m.start(), f"roster key `{key}` is not in the roster schema")
                break

    for off, span in blocks(bare, "Text"):
        if not re.search(r"\btextFormat\s*:\s*Text\.PlainText\b", bare[span]):
            err(off, "Text without `textFormat: Text.PlainText` (roster text is untrusted)")
    for m in re.finditer(r"\btextFormat\s*:(?!\s*Text\.PlainText\b)", bare):
        err(m.start(), "textFormat other than Text.PlainText")

    for off, span in blocks(bare, "PanelWindow"):
        if not NAMESPACE.search(code[span]):
            err(off, 'PanelWindow without `WlrLayershell.namespace: "qs-…"`')

    props = {m.group(1): m.group(2) for m in re.finditer(
        r"readonly\s+property\s+string\s+(\w+)\s*:\s*([^\n;]+)", bare)}
    for off, span in blocks(bare, "FileView"):
        m = PATH_BINDING.search(bare[span])
        if m and not safe_path(m.group(1), props):
            err(off, f"FileView path `{m.group(1).strip()}` is not built from literals/env/constants")

    for off, span in blocks(bare, "Process"):
        if "cava" not in code[span]:
            continue
        m = RUNNING_BINDING.search(bare[span])
        if not m or not VISIBILITY.search(m.group(1)):
            err(off, "cava Process.running must be bound to the sidebar's visibility")

    if rel not in GENERATED and rel not in PALETTES:
        for m in COLOUR_LITERAL.finditer(code):
            err(m.start(), "hard-coded colour outside Palette.qml (use Palette.*)")
    if not rel.startswith(("agents/", "bar/")) and rel != "desk/Hud.qml":
        for m in SIGNAL.finditer(bare):
            err(m.start(), "Palette.signal outside agents/, bar/ and desk/Hud.qml (the signal means: an agent waits)")
    for m in re.finditer(r'"([^"\n]*)"', code):
        if m.group(1) in words:
            err(m.start(), f"state word \"{m.group(1)}\" typed by hand: read it from Words (contracts words_es)")
    for m in BARE_PALETTE.finditer(bare):
        err(m.start(), "bare `Palette.` resolves to QtQuick's Palette: use `Ryce.Palette.` (import qs as Ryce)")
    return errs


def check(qml_dir: Path, schema_path: Path) -> list[str]:
    keys = schema_keys(json.loads(schema_path.read_text(encoding="utf-8")))
    words_file = qml_dir / "Words.qml"
    words = set(re.findall(r':\s*"([^"\n]+)"', words_file.read_text(encoding="utf-8"))) if words_file.is_file() else set()
    errs: list[str] = []
    for path in sorted(qml_dir.rglob("*.qml")):
        rel = path.relative_to(qml_dir).as_posix()
        if rel in GENERATED:
            continue
        errs += check_file(path, rel, keys, words)
    return errs


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    qml_dir, schema = Path(argv[1]), Path(argv[2])
    if not qml_dir.is_dir() or not schema.is_file():
        print(f"qmlcheck: need a QML dir and the roster schema, got {qml_dir} {schema}", file=sys.stderr)
        return 2
    errs = check(qml_dir, schema)
    for e in errs:
        print(e)
    if not errs:
        print(f"qmlcheck: ok ({sum(1 for _ in qml_dir.rglob('*.qml'))} files)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
